-- Single-use, expiring tokens that let a user set their own password (P0-02).
-- Only the SHA-256 (hex) of each token is stored. See docs/specs/password-lifecycle/spec.md.

CREATE TABLE password_setup_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL,
    created_at  TIMESTAMP   NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    used_at     TIMESTAMP,
    CONSTRAINT uq_password_setup_tokens_token_hash UNIQUE (token_hash)
);

-- Issuing a token deletes the user's unused ones.
CREATE INDEX idx_password_setup_tokens_user_id ON password_setup_tokens (user_id);
